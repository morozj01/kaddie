// Command crdpost finishes the CRDs controller-gen writes into a directory:
// it renames kaddie.org_<plural>.yaml to <plural>.yaml and adds the schema
// controller-gen can't express, which today is SREConfig's metadata.name
// restriction to "default" (base §6.1). It is idempotent.
package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	apiextensionsv1 "k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1"
	"sigs.k8s.io/yaml"
)

const prefix = "kaddie.org_"

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: crdpost <crd-dir>")
		os.Exit(2)
	}
	if err := run(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "crdpost:", err)
		os.Exit(1)
	}
}

func run(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if !strings.HasPrefix(e.Name(), prefix) {
			continue
		}
		src := filepath.Join(dir, e.Name())
		raw, err := os.ReadFile(src)
		if err != nil {
			return err
		}
		var crd apiextensionsv1.CustomResourceDefinition
		if err := yaml.UnmarshalStrict(raw, &crd); err != nil {
			return fmt.Errorf("%s: %w", src, err)
		}
		for i := range crd.Spec.Versions {
			// controller-gen writes an empty "subresources: {}" for types with
			// none; drop it so the CRD says exactly what it has.
			if sr := crd.Spec.Versions[i].Subresources; sr != nil && sr.Status == nil && sr.Scale == nil {
				crd.Spec.Versions[i].Subresources = nil
			}
		}
		if crd.Spec.Names.Kind == "SREConfig" {
			restrictName(&crd, "default")
		}
		out, err := yaml.Marshal(&crd)
		if err != nil {
			return err
		}
		// Drop the always-empty status stanza the typed round trip adds.
		out = bytes.Replace(out, []byte("status:\n  acceptedNames:\n    kind: \"\"\n    plural: \"\"\n  conditions: null\n  storedVersions: null\n"), nil, 1)
		header := []byte("# Generated by `make generate` from pkg/apis/v1alpha1. DO NOT EDIT.\n---\n")
		dst := filepath.Join(dir, strings.TrimPrefix(e.Name(), prefix))
		if err := os.WriteFile(dst, append(header, out...), 0o600); err != nil {
			return err
		}
		if err := os.Remove(src); err != nil {
			return err
		}
	}
	return nil
}

// restrictName limits metadata.name to one value in every served version.
func restrictName(crd *apiextensionsv1.CustomResourceDefinition, name string) {
	for i := range crd.Spec.Versions {
		s := crd.Spec.Versions[i].Schema.OpenAPIV3Schema
		md := s.Properties["metadata"]
		md.Type = "object"
		md.Properties = map[string]apiextensionsv1.JSONSchemaProps{
			"name": {
				Type:        "string",
				Description: "The only permitted name, so at most one SREConfig exists.",
				Enum:        []apiextensionsv1.JSON{{Raw: []byte(fmt.Sprintf("%q", name))}},
			},
		}
		s.Properties["metadata"] = md
	}
}
